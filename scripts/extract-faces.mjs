#!/usr/bin/env node
// Pulls the pixel-art robot faces out of the design SVG (design/robot-crew-1a.svg) and writes them as a TypeScript module.
//   node scripts/extract-faces.mjs design/robot-crew-1a.svg src/renderer/src/robots/faces.ts
// Each face becomes a grid of runs [x, y, w, h, colourIndex] in pixel units, plus its own colour palette.
// Header-sized copies ("face-*-header") are skipped: they are the same art drawn larger.
import { readFileSync, writeFileSync } from 'node:fs';

const [input, output] = process.argv.slice(2);
if (!input || !output) {
  console.error('usage: extract-faces.mjs <design.svg> <out.ts>');
  process.exit(1);
}

const svg = readFileSync(input, 'utf8');
const groupRe = /<g id="face-([a-z0-9-]+)"[^>]*>([\s\S]*?)<\/g>/g;
const rectRe = /<rect\b([^>]*)>/g;
const attr = (s, name) => {
  const m = new RegExp(`\\b${name}="([^"]*)"`).exec(s);
  return m ? m[1] : undefined;
};
const gcd = (a, b) => (b === 0 ? a : gcd(b, a % b));

const faces = {};
for (const [, id, body] of svg.matchAll(groupRe)) {
  if (id.endsWith('-header')) continue;
  const rects = [...body.matchAll(rectRe)].map(([, a]) => ({
    x: Number(attr(a, 'x')),
    y: Number(attr(a, 'y')),
    w: Number(attr(a, 'width')),
    h: Number(attr(a, 'height')),
    fill: attr(a, 'fill'),
  }));
  if (!rects.length) continue;
  for (const r of rects) {
    for (const v of [r.x, r.y, r.w, r.h]) {
      if (!Number.isInteger(v)) throw new Error(`face-${id}: non-integer coordinate ${v}`);
    }
    if (!/^#[0-9a-f]{6}$/i.test(r.fill ?? '')) throw new Error(`face-${id}: unexpected fill ${r.fill}`);
  }
  const minX = Math.min(...rects.map((r) => r.x));
  const minY = Math.min(...rects.map((r) => r.y));
  const maxX = Math.max(...rects.map((r) => r.x + r.w));
  const maxY = Math.max(...rects.map((r) => r.y + r.h));
  const unit = rects.reduce((g, r) => gcd(gcd(gcd(gcd(g, r.x - minX), r.y - minY), r.w), r.h), 0);
  const palette = [...new Set(rects.map((r) => r.fill.toLowerCase()))];
  faces[id] = {
    width: (maxX - minX) / unit,
    height: (maxY - minY) / unit,
    designPixel: unit,
    designOrigin: [minX, minY],
    palette,
    runs: rects.map((r) => [
      (r.x - minX) / unit,
      (r.y - minY) / unit,
      r.w / unit,
      r.h / unit,
      palette.indexOf(r.fill.toLowerCase()),
    ]),
  };
}

const ids = Object.keys(faces);
if (!ids.length) throw new Error('no faces found');

const lines = [
  '// Generated by scripts/extract-faces.mjs from design/robot-crew-1a.svg. Do not edit by hand.',
  '',
  'export interface FaceArt {',
  '  /** Grid size in art pixels. */',
  '  width: number;',
  '  height: number;',
  '  /** Size of one art pixel in the design, and where the face sits there (for layout checks). */',
  '  designPixel: number;',
  '  designOrigin: readonly [number, number];',
  '  palette: readonly string[];',
  '  /** Runs of same-coloured pixels: [x, y, w, h, paletteIndex]. */',
  '  runs: readonly (readonly [number, number, number, number, number])[];',
  '}',
  '',
  `export const FACES = {`,
  ...ids.map((id) => {
    const f = faces[id];
    return [
      `  ${JSON.stringify(id)}: {`,
      `    width: ${f.width},`,
      `    height: ${f.height},`,
      `    designPixel: ${f.designPixel},`,
      `    designOrigin: [${f.designOrigin.join(', ')}],`,
      `    palette: ${JSON.stringify(f.palette)},`,
      `    runs: [${f.runs.map((r) => `[${r.join(',')}]`).join(',')}],`,
      `  },`,
    ].join('\n');
  }),
  `} as const satisfies Record<string, FaceArt>;`,
  '',
  'export type FaceId = keyof typeof FACES;',
  '',
];
writeFileSync(output, lines.join('\n'));
for (const id of ids) {
  const f = faces[id];
  console.log(
    `${id.padEnd(8)} ${f.width}x${f.height} px=${f.designPixel} at ${f.designOrigin.join(',')} colours=${f.palette.length} runs=${f.runs.length}  ${f.palette.join(' ')}`,
  );
}
